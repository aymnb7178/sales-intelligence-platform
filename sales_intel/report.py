def _b64(path: Path) -> str:
    return base64.b64encode(path.read_bytes()).decode("ascii")


def _img(path: Path, alt: str) -> str:
    return f'<img alt="{html.escape(alt)}" src="data:image/png;base64,{_b64(path)}">'


def _table(df: pd.DataFrame, float_fmt: str = "{:,.2f}") -> str:
    return df.to_html(index=False, border=0, escape=True, float_format=lambda v: float_fmt.format(v))


def _fmt_money(v: float) -> str:
    return f"{v:,.0f}"


def build_dashboard(a: Analysis, charts: dict[str, Path], out_path: Path) -> Path:
    """Write the dashboard HTML to ``out_path`` and return the path."""
    k = a.kpis
    yoy = k.get("yoy_growth_last_12m_pct")
    cards = [
        ("Revenue", _fmt_money(k["revenue"])),
        ("Gross profit", _fmt_money(k["gross_profit"])),
        ("Gross margin", f"{k['gross_margin_pct']:.1f}%"),
        ("Orders", f"{k['orders']:,}"),
        ("Customers", f"{k['customers']:,}"),
        ("Avg order value", f"{k['avg_order_value']:,.2f}"),
        ("Repeat customers", f"{k['repeat_customer_rate_pct']:.1f}%"),
        ("YoY (last 12m)", f"{yoy:+.1f}%" if yoy is not None else "n/a"),
    ]
    kpi_html = "".join(f'<div class="kpi"><div class="v">{html.escape(v)}</div><div class="l">{html.escape(l)}</div></div>' for l, v in cards)

    bt = a.backtest
    bt_rows = pd.DataFrame(
        {"model": list(bt.metrics), "MAPE %": [round(v, 2) for v in bt.metrics.values()]}
    ).sort_values("MAPE %")
    seg_tbl = _table(a.rfm_summary)
    section = lambda title, body: f"<h2>{html.escape(title)}</h2>{body}"  # noqa: E731

    body = f"""
<h1>Sales Intelligence Dashboard</h1>
<p class="sub">Data window {html.escape(str(k['first_order_date']))} to {html.escape(str(k['last_order_date']))}.</p>
<div class="note"><strong>Synthetic data.</strong> Every number here comes from a randomly generated dataset. It illustrates the pipeline and does not describe any real business.</div>
<div class="kpis">{kpi_html}</div>
{section("Revenue and forecast", '<div class="card">' + _img(charts["revenue_forecast"], "Revenue forecast") + "</div>")}
{section(f"Forecast backtest (last {bt.holdout} months held out)",
    '<div class="grid2"><div class="card">' + _img(charts["backtest"], "Backtest") + '</div><div class="card">' + _table(bt_rows)
    + f"<p>Best model on this holdout: <strong>{html.escape(bt.best_model)}</strong>. Single holdout, so indicative only.</p></div></div>")}
{section("Products", '<div class="grid2"><div class="card">' + _img(charts["top_products"], "Top products") + '</div><div class="card">' + _img(charts["category_margin"], "Margin by category") + "</div></div>")}
{section("ABC analysis", '<div class="card">' + _img(charts["abc_analysis"], "ABC analysis") + "</div>")}
{section("Customer segments (RFM)", '<div class="card">' + _img(charts["rfm_segments"], "RFM segments") + "</div>" + '<div class="card">' + seg_tbl + "</div>")}
{section("Cohort retention", '<div class="card">' + _img(charts["cohort_retention"], "Cohort retention heatmap") + "</div>")}
{section("Top products table", '<div class="card">' + _table(a.top_products) + "</div>")}
<footer>Generated by Sales Intelligence Platform. Self-contained: no scripts or external requests.</footer>
"""
    doc = (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>Sales Intelligence Dashboard</title><style>{CSS}</style></head><body><main>{body}</main></body></html>"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(doc, encoding="utf-8")
    return out_path
